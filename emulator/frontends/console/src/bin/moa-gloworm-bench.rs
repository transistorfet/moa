const CMDLINE_LEN: u32 = 32;
const EMU_INTERVAL: Duration = Duration::from_millis(10); // ms

#[derive(Parser, Debug)]
#[command(about = "A configurable test bench for gloworm on different Motorola 68000 processors", long_about = None)]
struct BenchConfig {
    // startup config
    #[arg(help = "Binary file to be loaded into the emulator")]
    bin: String,

    #[arg(long, short, help = "Configure emu with a config file generated by the gloworm make system")]
    config_file: Option<String>,

    //#[arg(long, help = "Commandline to be given to kernel", default_value_t = String::from(""))]
    //command_line: String,

    #[arg(long, help = "Physical address where the binary will be loaded", default_value_t = 0)]
    bin_load_address: u32,

    // periphery (bus) config
    #[arg(long, help = "Physical start address of RAM", default_value_t = 0)]
    ram_address: u32,

    #[arg(long, help = "Length of RAM in bytes", default_value_t = 0)]
    ram_length: u32,

    #[arg(long, help = "Address of the mc68681 DUART, 0 means disabled", default_value_t = 0)]
    mc68681_addr: u32,

    #[arg(long, help = "(External) Prescaler of the mc68681 timer", default_value_t = 32)] // 3686400/32/1152 = 100
    mc68681_prescaler: u16,

    #[arg(long, help = "Address of the memory mapped ATA device", default_value_t = 0)]
    ata_addr: u32,

    #[arg(long, help = "Image file for the ATA device")]
    ata_img: Option<String>,

    // CPU config
    #[arg(long, default_value_t = 8.0, help = "Clock speed of the emulated CPU, in MHz")]
    clock_speed: f64,

    #[arg(long, help = "Initial stack pointer of the CPU, defaults to end of RAM")]
    isp: Option<u32>,

    #[arg(long, help = "Initial program counter of the CPU, defaults to binary load address")]
    ipc: Option<u32>,

    #[arg(value_enum, long, default_value_t = CpuType::MC68010, help = "The architecture of the emulated CPU")]
    cpu_type: CpuType,

    // Emu config
    #[arg(long, default_value_t = 10.0f64, help = "Runtime of the emulation, in seconds (0 means run forever)")]
    runtime: f64,

    #[arg(long, short, default_value_t = false, help = "Run the emulator in interactive mode (read from stdin), this also makes the emulator run forever")]
    interactive: bool,

    #[arg(long, help = "Feed the DUART with data from this file, can be used together with -i")]
    input_file: Option<String>
}

#[derive(Debug, Copy, Clone, PartialEq, Eq, PartialOrd, Ord, ValueEnum)]
enum CpuType {
    MC68000,
    MC68008,
    MC68010,
    MC68020,
    MC68030,
}

impl CpuType {
    pub fn to_m68k_type(&self) -> M68kType {
        match self {
            CpuType::MC68000 => M68kType::MC68000,
            CpuType::MC68008 => M68kType::MC68008,
            CpuType::MC68010 => M68kType::MC68010,
            CpuType::MC68020 => M68kType::MC68020,
            CpuType::MC68030 => M68kType::MC68030,
        }
    }
}

struct CurrentTty {
    uart_sender: Sender<u8>,
    uart_receiver: Receiver<u8>,
    term: Term
}

impl CurrentTty {
    // Prefeed channel (misused as buffer) 
    pub fn prefeed(&mut self, data: &Vec<u8>) {
        for byte in data {
            self.uart_sender.send(*byte).unwrap();
        }
    }

    // Spawn thread for reading UART input from stdin
    pub fn start_interaction(&mut self) {

        let term_local = self.term.clone();
        let sender_local = self.uart_sender.clone();
        thread::spawn(move || {
            loop {
                sender_local.send(term_local.read_char().unwrap() as u8).unwrap();
            }
        });
    }
}

impl Default for CurrentTty {
    fn default() -> Self {
        let (uart_sender, uart_receiver) = mpsc::channel::<u8>();
        Self { uart_sender, uart_receiver, term: Term::stdout() }
    }
}

impl Tty for CurrentTty {
    fn device_name(&self) -> String {
        "CurrentTTY".to_owned()
    }

    fn read(&mut self) -> Option<u8> {
        if let Ok(byte) = self.uart_receiver.try_recv() {
            Some(byte)
        } else {
            None
        }
    }

    fn write(&mut self, output: u8) -> bool {
        self.term.write_all(&[output]).unwrap();
        self.term.flush().unwrap();
        true
    }
}

fn parse_hex(val: &str) -> u32 {
    let s = val.trim();
    if s.len() >= 3 && (&s[0..2] == "0x") {
        match u32::from_str_radix(&s[2..], 16) {
            Ok(v) => v,
            Err(e) => {
                println!("Warning: invalid hex '{}': {}", val, e);
                0
            }
        }
    } else {
        println!("Warning: invalid hex '{}': must start with 0x", val);
        0
    }
}

// Configure the addresses for the emulator via a config file
fn set_args_from_file(args: &mut BenchConfig) {
    let file = args.config_file.as_ref().unwrap();

    for line in fs::read_to_string(file).unwrap().lines() {
        // skip comments and empty lines
        if line.starts_with("#") || line.len() == 0 {
            continue;
        }

        let kv: Vec<&str> = line.split("=").collect();
        if kv.len() != 2 {
            println!("Warning: invalid line in config: {}", line);
            continue;
        }

        match kv.as_slice() {
            // binary load address & ram start
            ["CONFIG_KERNEL_BASE", val] => { 
                args.bin_load_address = parse_hex(val);
                args.ram_address = parse_hex(val);
            }

            ["CONFIG_KERNEL_RAM_SIZE", val] => { args.ram_length = parse_hex(val) }
            ["CONFIG_TTY_68681_BASE", val] => { args.mc68681_addr = parse_hex(val) - 1 } // Value in config is physical base + 1
            ["CONFIG_ATA_BASE", val] => { args.ata_addr = parse_hex(val) - 0x21 } // Value in config is physical base + 0x21

            // CPU types
            ["CONFIG_MC68010", "y"] => { args.cpu_type = CpuType::MC68010; }
            ["CONFIG_MC68020", "y"] => { args.cpu_type = CpuType::MC68020; }
            ["CONFIG_MC68030", "y"] => { args.cpu_type = CpuType::MC68030; }

            _ => {}
        }
    }
}

fn main() {
    let mut args = BenchConfig::parse();
    // Read the emu config from the .config if wanted
    if args.config_file.is_some() {
        set_args_from_file(&mut args);
    }

    // Test if required parameters are set
    if args.ram_length == 0 {
        println!("Error: RAM size must be greater than 0!");
        return;
    }

    // Test if required parameters are set
    if args.bin_load_address == 0 {
        println!("Error: Loading the binary at address 0 overwrites vector table!");
        return;
    }

    // Stack pointer is initially at top of RAM
    let mut isp_address = args.isp.unwrap_or(args.ram_address + args.ram_length);

    let mut system = System::default();
    let mut ram = MemoryBlock::new(vec![0; args.ram_length as usize]);
    ram.load_at((args.bin_load_address - args.ram_address) as u64, &args.bin).unwrap();

    
    // Paste kernel command line to top of stack, not actually working, thus commented out
    isp_address -= CMDLINE_LEN;
    /*
    let mut i = 0;
    for c in args.command_line.into_bytes() {
        if i >= CMDLINE_LEN - 1 { // keep one byte for \0
            break;
        }
        ram.write_u8(Instant::START, (isp_address + i - args.ram_address) as u64, c).unwrap();
        i += 1;
    }
    // Null termination
    ram.write_u8(Instant::START, (isp_address + i - args.ram_address) as u64, 0x00).unwrap();
    */
    // Space for return pointer set by bootloader, empty here because we don't have a bootloader
    isp_address -= 4;

    // Add initial stack pointer & initial program counter to vector table (VT isn't included in gloworm)
    if args.ram_address == 0x00 { // Add vectors to ram if ram is mapped to initial vector table
        ram.write_beu32(Instant::START, 0x00, isp_address).unwrap();
        ram.write_beu32(Instant::START, 0x04, args.ipc.unwrap_or(args.bin_load_address)).unwrap();
    } else { // Generate a seperate vector area
        let mut vt = MemoryBlock::new(vec![0; 8]);
        vt.write_beu32(Instant::START, 0x00, isp_address).unwrap();
        vt.write_beu32(Instant::START, 0x04, args.ipc.unwrap_or(args.bin_load_address)).unwrap();
        system.add_addressable_device(0x00u64, Device::new(vt)).unwrap();
    }

    system.add_addressable_device(args.ram_address as u64, Device::new(ram)).unwrap();

    // Add the DUART when necessary
    if args.mc68681_addr != 0 {
        let mut serial = MC68681::default();
        serial.timer_prescaler = args.mc68681_prescaler; 
        let mut current_tty = CurrentTty::default();

        if let Some(file) = args.input_file {
            let data: Vec<u8> = fs::read_to_string(file).unwrap().bytes().collect();
            current_tty.prefeed(&data);
        }

        if args.interactive {
            current_tty.start_interaction();
        }

        serial.port_a.connect(Box::new(current_tty)).unwrap();
        system.add_addressable_device(args.mc68681_addr as u64, Device::new(serial)).unwrap();
    }

    // Add the ATA device if necessary
    if let Some(ata_img) = args.ata_img {
        if args.ata_addr == 0 {
            println!("Error: ATA base address not set!");
            return;
        }

        let mut ata = AtaDevice::default();
        ata.load(&ata_img).unwrap();
        system.add_addressable_device(args.ata_addr as u64, Device::new(ata)).unwrap();
    }

    let cpu = M68k::from_type(args.cpu_type.to_m68k_type(), Frequency::from_hz((args.clock_speed * 1e6) as u32));
    system.add_interruptable_device("cpu", Device::new(cpu)).unwrap();

    if args.runtime == 0.0f64 || args.interactive {
        loop {
            let current_cycle_start = SystemTime::now();
            system.run_for_duration(femtos::Duration::from(EMU_INTERVAL)).unwrap();
            let time_elapsed = current_cycle_start.elapsed().unwrap();
            let sleep_time = EMU_INTERVAL.saturating_sub(time_elapsed);

            if !sleep_time.is_zero() {
                sleep(sleep_time);
            }
        }
    } else {
        system.run_for_duration(femtos::Duration::from_millis((args.runtime * 1000.0) as u64)).unwrap();
    }
}